"""Three evaluations of chat2faq on the sample, written to results/evaluation.md.

1. clean: the 40 nakli exports as generated, scored against nakli's per-line labels.
2. messy: the same conversations made to look like real exports (seed 11): half moved to
   the iOS format with narrow no-break spaces and direction marks, some customers saved as
   bare phone numbers, a BOM and CRLF on some files, "?" dropped from 40% of customer
   messages, a typo in 15%, emoji on 20%, and media/deleted/"ok" lines between messages.
   Labels follow their lines, so the scores are comparable.
3. probe: 48 questions written for this evaluation (examples/probe.jsonl), in other words
   and scripts than nakli's templates, answered by the FAQ built from the clean sample, at
   several similarity thresholds.

    python tools/evaluate.py
"""

from __future__ import annotations

import random
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from chat2faq.evaluate import load_labels, load_probe, probe_score, score  # noqa: E402
from chat2faq.mine import pair  # noqa: E402
from chat2faq.parse import parse_path  # noqa: E402

BUSINESS = "Indigo Loom"
LINE = re.compile(r"^(\d+/\d+/\d+), (\d+):(\d+)[ \u202f]([ap]m) - (?:([^:]+): )?(.*)$")
NNBSP, LRM, LRE, PDF = " ", "‎", "‪", "‬"


def line(ios: bool, phone: str | None, d, h, m, ap, who, text) -> str:
    name = who
    if phone and who != BUSINESS:
        name = f"{LRE}{phone[:3]} {phone[3:8]} {phone[8:]}{PDF}"
    stamp = f"[{d}, {h}:{m}:00{NNBSP}{ap.upper()}]" if ios else f"{d}, {h}:{m}{NNBSP}{ap} -"
    return f"{stamp} {name}: {text}" if who else f"{stamp} {text}"


def mess(src: Path, dst: Path, labels: dict, rng: random.Random) -> dict:
    """Write messy copies of every export in src to dst; return labels for the new lines."""
    out_labels = {}
    for f in sorted(src.glob("*.txt")):
        ios = rng.random() < 0.5
        phone = f"+91 9{rng.randrange(10**8, 10**9)}" if rng.random() < 0.3 else None
        lines: list[str] = []
        for n, raw in enumerate(f.read_text(encoding="utf-8").splitlines(), start=1):
            m = LINE.match(raw)
            if not m:
                lines.append(raw)
                continue
            d, h, mi, ap, who, text = m.groups()
            if not who:  # the encryption banner; iOS writes it with the contact as sender
                who = f.stem.removeprefix("WhatsApp Chat with ") if ios else None
                lines.append(line(ios, phone, d, h, mi, ap, who, text))
                continue
            customer = who != BUSINESS
            if customer:
                if rng.random() < 0.4:
                    text = text.replace("?", "")
                if rng.random() < 0.15:
                    words = text.split()
                    k = rng.randrange(len(words))
                    w = words[k]
                    if len(w) >= 4:
                        j = rng.randrange(len(w) - 1)
                        words[k] = w[:j] + w[j + 1] + w[j] + w[j + 2 :]
                    text = " ".join(words)
                if rng.random() < 0.2:
                    text += " " + rng.choice(["🙏", "😊", "👍🏻"])
            lines.append(line(ios, phone, d, h, mi, ap, who, text))
            if (f.name, n) in labels:
                out_labels[(f.name, len(lines))] = labels[(f.name, n)]
            if customer and rng.random() < 0.2:
                noise = rng.choice(["<Media omitted>", "ok", "This message was deleted"])
                lines.append(line(ios, phone, d, h, mi, ap, who, LRM + noise if ios else noise))
        crlf = rng.random() < 0.3
        data = ("\r\n" if crlf else "\n").join(lines) + ("\r\n" if crlf else "\n")
        (dst / f.name).write_bytes(data.encode("utf-8-sig" if rng.random() < 0.3 else "utf-8"))
    return out_labels


def row(name: str, r: dict) -> str:
    return (
        f"| {name} | {r['question_recall']}% | {r['purity']}% ({r['entries']} entries) | "
        f"{r['intents_with_entry']}/{r['intents']} | {r['heldout_covered']}/{r['heldout']} |"
    )


def main() -> None:
    exports, labels_path = ROOT / "examples/exports", ROOT / "examples/labels.jsonl"
    labels = load_labels(labels_path)
    clean = score(pair(parse_path(exports), BUSINESS), labels)
    with tempfile.TemporaryDirectory() as d:
        messy_labels = mess(exports, Path(d), labels, random.Random(11))
        messy_msgs = parse_path(Path(d))
        messy = score(pair(messy_msgs, BUSINESS), messy_labels)
    probes = load_probe(ROOT / "examples/probe.jsonl")
    qas = pair(parse_path(exports), BUSINESS)
    out = [
        "# Evaluation",
        "",
        "Generated by `python tools/evaluate.py`. Do not edit by hand.",
        "",
        "| Data | Question recall | Entry purity | Intents with an entry | Held-out covered |",
        "|---|---|---|---|---|",
        row("clean sample", clean),
        row("messy copy (seed 11)", messy),
        "",
        f"Probe: {len(probes)} questions written independently of the sample's templates.",
        "",
        "| Threshold | Right entry | Wrong entry | No entry |",
        "|---|---|---|---|",
    ]
    for t in (0.15, 0.2, 0.25, 0.3, 0.35, 0.4):
        r = probe_score(qas, labels, probes, t)
        out.append(f"| {t} | {r['right']} | {len(r['wrong'])} | {len(r['unanswered'])} |")
    r = probe_score(qas, labels, probes, 0.3)
    out += ["", "Wrong answers at the default threshold (0.3):", ""]
    out += [f"- {q!r} went to the {intent} entry" for q, intent in r["wrong"]]
    (ROOT / "results/evaluation.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
